function dataUrlBytes(dataUrl) {
  const b64 = dataUrl.split(',')[1] || '';
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

// Returns { files: [{path, data}], report: {ok, errors, warnings}, zip(): Uint8Array }
export function buildPackage({ model, animations, modId = 'yourmod', entityName, target = 'geckolib4', include = {} }) {
  const inc = { model: true, animations: true, texture: true, bbmodel: true, java: true, readme: true, ...include };
  const T = TARGETS[target] || TARGETS.geckolib4;
  const mod = cleanId(modId).replace(/[.-]/g, '_');
  const name = cleanId(entityName || model.name).replace(/[.-]/g, '_');
  const p = T.paths(mod, name);
  const files = [];
  const errors = [], warnings = [];

  const geo = exportGeo(model, `geometry.${name}`);
  const gv = validateGeo(geo);
  errors.push(...gv.errors.map((e) => `geo.json: ${e}`)); warnings.push(...gv.warnings);
  if (inc.model) files.push({ path: p.geo, data: geo });

  const animFile = exportAnimationFile(name, animations);
  if (inc.animations) {
    const av = validateAnimationFile(animFile, geo);
    errors.push(...av.errors.map((e) => `animation.json: ${e}`)); warnings.push(...av.warnings);
    const ids = Object.keys(animFile.animations);
    if (new Set(ids).size !== animations.length) errors.push('Two animations end up with the same ID – rename one.');
    files.push({ path: p.anim, data: animFile });
  }
  if (inc.texture) {
    if (model.texture?.dataUrl) files.push({ path: p.tex, data: dataUrlBytes(model.texture.dataUrl) });
    else warnings.push('No texture loaded – add your PNG manually.');
  }
  if (inc.bbmodel) files.push({ path: target === 'raw' ? `${name}.bbmodel` : `extras/${name}.bbmodel`, data: exportBBModel(model, animations) });
  if (inc.java && T.java) files.push({ path: `extras/java/${javaName(name)}Animations.java`, data: T.java({ entityName: name, animations, modelName: name }) });

  const report = { ok: errors.length === 0, errors, warnings };
  if (inc.readme) files.push({ path: target === 'raw' ? 'README.md' : 'README.md', data: readme({ T, mod, name, p, animations, report, files }) });
  return { files, report, zip: () => createZip(files) };
}

function readme({ T, mod, name, p, animations, report, files }) {
  const rows = animations.map((a) => `| \`${animationId(name, a.name)}\` | ${a.length.toFixed(2)}s | ${a.loop === 'loop' ? 'loops' : a.loop === 'hold' ? 'holds last frame' : 'plays once'} |`).join('\n');
  return `# ${name} – animation export

Target: **${T.label}**
Generated by Minecraft Animation Studio.

## Files
${files.map((f) => `- \`${f.path}\``).join('\n')}

## Install
${T.short === 'Raw JSON' ? '- Copy the JSON files wherever your loader expects them.' : `1. Copy the \`src/\` folder over your mod project (the paths already include \`assets/${mod}/\`).
2. If your mod id isn't \`${mod}\`, re-export with the right id (or rename the \`${mod}\` folder).
3. Copy \`extras/java/*Animations.java\` into your client code and fix its \`package\` line.`}
${T.notes(mod, name).map((n) => `- ${n}`).join('\n')}

## Animations
| ID | Length | Loop |
|---|---|---|
${rows}

## Validation
${report.ok ? 'Passed: the files match the GeckoLib animation/geometry format checks.' : `**Failed:**\n${report.errors.map((e) => `- ${e}`).join('\n')}`}
${report.warnings.length ? `\nWarnings:\n${report.warnings.map((w) => `- ${w}`).join('\n')}` : ''}

\`extras/${name}.bbmodel\` opens in Blockbench (with the GeckoLib plugin) if you want to keep editing there.
`;
}
