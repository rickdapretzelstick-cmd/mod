// Export adapters. Each target knows where files go in a mod's resources and how the Java
// glue code looks. Add a new framework by adding an entry to TARGETS.
import { exportAnimationFile, validateAnimationFile, validateGeo, animationId } from '../formats/geckolib.js';
import { exportGeo } from '../formats/geo.js';
import { exportBBModel } from '../formats/bbmodel.js';
import { createZip } from './zip.js';

const javaName = (s) => String(s).replace(/(^|[_\s.-]+)([a-z0-9])/gi, (_, __, c) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, '') || 'Model';
const CONST = (s) => String(s).toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '') || 'ANIM';
export const cleanId = (s) => String(s).toLowerCase().trim().replace(/[^a-z0-9_.-]+/g, '_').replace(/^_+|_+$/g, '') || 'unnamed';

function rawLine(a, id) {
  const kind = a.loop === 'loop' ? 'thenLoop' : a.loop === 'hold' ? 'thenPlayAndHold' : 'thenPlay';
  return `    public static final RawAnimation ${CONST(a.name)} = RawAnimation.begin().${kind}("${id}");`;
}

function javaClass({ entityName, animations, modelName, v5 }) {
  const cls = `${javaName(entityName)}Animations`;
  const lines = animations.map((a) => rawLine(a, animationId(modelName, a.name)));
  const loopers = animations.filter((a) => a.loop === 'loop');
  const idle = loopers.find((a) => /idle/.test(a.name)) || loopers[0];
  const walk = loopers.find((a) => /walk|run/.test(a.name));
  const triggers = animations.filter((a) => a.loop !== 'loop');
  const ctor = v5 ? 'new AnimationController<>("main", 5, state ->' : 'new AnimationController<>(this, "main", 5, state ->';
  const base = idle ? (walk ? `state.setAndContinue(state.isMoving() ? ${cls}.${CONST(walk.name)} : ${cls}.${CONST(idle.name)})` : `state.setAndContinue(${cls}.${CONST(idle.name)})`) : 'PlayState.STOP';
  const trig = triggers.map((a) => `\n//         .triggerableAnim("${cleanId(a.name)}", ${cls}.${CONST(a.name)})`).join('');
  return `// Generated by Minecraft Animation Studio for GeckoLib ${v5 ? '5.x' : '4.x'}.
// Move this into your mod's source tree and fix the package line.
package com.example.yourmod.client;

import ${v5 ? 'com.geckolib' : 'software.bernie.geckolib'}.animation.RawAnimation;

public final class ${cls} {
${lines.join('\n')}

    private ${cls}() {}
}

// ---- How to use it in your GeoEntity / GeoAnimatable -------------------------------------
//
// @Override
// public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
//     controllers.add(${ctor} ${base})${trig});
// }
//
// Fire a one-shot animation from the server side (synced to clients automatically):
${triggers.slice(0, 3).map((a) => `//     this.triggerAnim("main", "${cleanId(a.name)}");`).join('\n') || '//     (no one-shot animations exported)'}
`;
}

